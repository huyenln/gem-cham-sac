-- Kho vải: the real fabrics Gem has, for the design table (studio.html,
-- Bàn thiết kế) and the admin tab "Kho vải".
--
-- fabrics          customers read every row (a shared design keeps its
--                  photo even after the fabric runs out); staff write.
-- fabric_private   where the fabric is kept at Gem: staff only. Customers
--                  never see it, so it lives in its own table rather than a
--                  column (RLS filters rows, not columns).
--
-- Run once in Supabase → SQL Editor, then the GRANT-vs-policy check in
-- docs/design.md: it must show no row for fabrics / fabric_private.
-- The existing photographed fabrics are seeded by 20261014b_kho_vai_seed.sql.

create table if not exists public.fabrics (
  id          int generated by default as identity primary key,
  name_vi     text not null check (char_length(name_vi) between 1 and 60),
  name_en     text check (char_length(name_en) <= 60),
  tone        text not null check (tone in ('xanh','lam','hong','nau','trung')),
  kind        text not null default 'tron'
              check (kind in ('tron','caro','soc','cham','hoa','ren','hoato','ono','tho')),
  material    text check (char_length(material) <= 40),
  -- a 320px square photo: a file in the repo (images/…) or one uploaded to
  -- the public bucket gem-media. Nothing else, so the page never loads a
  -- picture from a site it does not know.
  img         text not null check (
                img ~ '^images/[a-z0-9/_.-]+$' or
                img ~ '^https://dxdovvqsfjeizsoprrfn\.supabase\.co/storage/v1/object/public/gem-media/[A-Za-z0-9%._-]+$'),
  in_stock    boolean not null default true,
  is_visible  boolean not null default true,   -- false: never offered in the basket
  sort_order  int not null default 0,
  created_at  timestamptz not null default now()
);

create table if not exists public.fabric_private (
  fabric_id   int primary key references public.fabrics(id) on delete cascade,
  place       text check (char_length(place) <= 120)
);

alter table public.fabrics enable row level security;
alter table public.fabric_private enable row level security;

create policy fab_read_all     on public.fabrics for select to anon, authenticated using (true);
create policy fab_insert_staff on public.fabrics for insert to authenticated with check (is_staff());
create policy fab_update_staff on public.fabrics for update to authenticated using (is_staff()) with check (is_staff());
create policy fab_delete_staff on public.fabrics for delete to authenticated using (is_staff());

create policy fp_select_staff on public.fabric_private for select to authenticated using (is_staff());
create policy fp_insert_staff on public.fabric_private for insert to authenticated with check (is_staff());
create policy fp_update_staff on public.fabric_private for update to authenticated using (is_staff()) with check (is_staff());
create policy fp_delete_staff on public.fabric_private for delete to authenticated using (is_staff());

-- RLS filters ROWS, GRANT opens the DOOR: both are needed.
grant select on public.fabrics to anon, authenticated;
grant insert, update, delete on public.fabrics to authenticated;
grant select, insert, update, delete on public.fabric_private to authenticated;
-- anon gets nothing on fabric_private: "permission denied" before RLS.
